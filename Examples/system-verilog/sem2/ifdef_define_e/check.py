#!/usr/bin/env python3
"""Check Slang ``-D`` extraction and both simulator preprocessor branches."""

from pathlib import Path
import os
import shutil
import signal
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "harness/sv"))
from xcelium_probe import probe_xcelium  # noqa: E402

EXPECTED_FEATURE = [
    ["zero", "0", "0"],
    ["one", "1", "1"],
    ["x", "x", "x"],
    ["z", "z", "z"],
]
EXPECTED_PLAIN = [
    ["zero", "0", "1"],
    ["one", "1", "0"],
    ["x", "x", "x"],
    ["z", "z", "x"],
]


def run(args, cwd=ROOT):
    proc = subprocess.Popen(args, cwd=cwd, text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            start_new_session=True)
    try:
        out, err = proc.communicate(timeout=120)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(proc.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        out, err = proc.communicate()
        raise RuntimeError(f"{args[0]} timed out:\n{out}{err}")
    if proc.returncode:
        raise RuntimeError(f"{args[0]} exited {proc.returncode}:\n{out}{err}")
    return out, err


def rows(output):
    answer = []
    for line in output.splitlines():
        if not line.startswith("ROW "):
            continue
        fields = line.split()
        answer.append([fields[1]] + [x.split("=", 1)[1] for x in fields[2:]])
    return answer


def check_envelope():
    with tempfile.TemporaryDirectory(prefix="sv-ifdef-envelope-") as work:
        output = Path(work) / "ifdef_define_e.sv.json"
        run([sys.executable, str(ROOT / "extractors/sv/extract.py"),
             "--top", "ifdef_define_e", "-D", "FEATURE=1", "-o", str(output),
             str((HERE / "ifdef_define_e.sv").relative_to(ROOT))])
        recorded = HERE / "ifdef_define_e.sv.json"
        if output.read_bytes() != recorded.read_bytes():
            raise RuntimeError("FEATURE envelope is not byte-identical to extraction")
    print("Slang -D FEATURE=1 envelope regenerated byte-identically")


def source_rows(simulator, feature):
    sources = [str(HERE / "ifdef_define_e.sv"),
               str(HERE / "ifdef_define_e_tb.sv")]
    with tempfile.TemporaryDirectory(prefix="sv-ifdef-rows-") as work:
        define = ["-DFEATURE=1"] if feature else []
        if simulator == "iverilog":
            exe = str(Path(work) / "sim")
            run(["iverilog", "-g2012", "-s", "ifdef_define_e_tb",
                 "-o", exe] + define + sources, work)
            output, _ = run(["vvp", exe], work)
        else:
            output, _ = run(["xrun", "-sv", "-q", "-timescale", "1ns/1ps",
                             *( ["-define", "FEATURE=1"] if feature else []),
                             "-top", "ifdef_define_e_tb"] + sources, work)
    return rows(output)


def main():
    check_envelope()
    run(["lake", "env", "lean",
         "Examples/system-verilog/sem2/ifdef_define_e/agree.lean"])
    print("E preprocessor fixture: PASS")
    if not shutil.which("iverilog") or not shutil.which("vvp"):
        raise RuntimeError("Icarus is required")
    version, err = run(["iverilog", "-V"])
    print((version + err).splitlines()[0])
    simulators = ["iverilog"]
    if shutil.which("xrun"):
        status, details = probe_xcelium()
        print(details)
        if status == 0:
            version, err = run(["xrun", "-version"])
            print((version + err).strip())
            simulators.append("xrun")
        elif status == 77:
            print("no Xcelium result: explicit license refusal")
        else:
            raise RuntimeError("Xcelium readiness probe failed")
    else:
        print("no Xcelium result: xrun unavailable")
    for simulator in simulators:
        for feature, expected in ((True, EXPECTED_FEATURE),
                                  (False, EXPECTED_PLAIN)):
            actual = source_rows(simulator, feature)
            if actual != expected:
                raise RuntimeError(f"{simulator} {'FEATURE' if feature else 'plain'}: "
                                   f"expected {expected}, got {actual}")
            label = "FEATURE=1" if feature else "no FEATURE"
            print(f"{simulator} {label}: {len(actual)} rows MATCH")


if __name__ == "__main__":
    main()
