#!/usr/bin/env python3
"""Check the retained net-declaration boundary and source simulator rows."""

from pathlib import Path
import os
import shutil
import signal
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "harness/sv"))
from xcelium_probe import probe_xcelium  # noqa: E402

EXPECTED = [
    ["zero", "0"],
    ["one", "1"],
    ["x", "x"],
    ["z", "z"],
]


def run(args, cwd=ROOT):
    process = subprocess.Popen(args, cwd=cwd, text=True,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                               start_new_session=True)
    try:
        stdout, stderr = process.communicate(timeout=120)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        stdout, stderr = process.communicate()
        raise RuntimeError(f"{args[0]} timed out:\n" + stdout + stderr)
    if process.returncode:
        raise RuntimeError(f"{args[0]} exited {process.returncode}:\n" + stdout + stderr)
    return stdout


def rows(output):
    answer = []
    for line in output.splitlines():
        if line.startswith("ROW "):
            fields = line.split()
            answer.append([fields[1], fields[2].split("=", 1)[1]])
    return answer


def check_envelope():
    with tempfile.TemporaryDirectory(prefix="sv-net-decl-envelope-") as work:
        output = Path(work) / "net_decl_alias_e.sv.json"
        run([sys.executable, str(ROOT / "extractors/sv/extract.py"),
             "--top", "net_decl_alias_e", "--retain-proc-rewrites",
             "-o", str(output),
             str((HERE / "net_decl_alias_e.sv").relative_to(ROOT))])
        recorded = HERE / "net_decl_alias_e.sv.json"
        if output.read_bytes() != recorded.read_bytes():
            raise RuntimeError("retained envelope is not byte-identical to extraction")
    print("retained envelope regenerated byte-identically")


def source_rows(simulator):
    sources = [str(HERE / "net_decl_alias_e.sv"),
               str(HERE / "net_decl_alias_e_tb.sv")]
    with tempfile.TemporaryDirectory(prefix="sv-net-decl-") as work:
        if simulator == "iverilog":
            exe = str(Path(work) / "sim")
            run(["iverilog", "-g2012", "-s", "net_decl_alias_e_tb",
                 "-o", exe] + sources, work)
            output = run(["vvp", exe], work)
        else:
            output = run(["xrun", "-sv", "-q", "-timescale", "1ns/1ps",
                          "-top", "net_decl_alias_e_tb"] + sources, work)
    return rows(output)


def main():
    check_envelope()
    run(["lake", "build", "Examples.«system-verilog».sem2.net_decl_alias_e.agree"])
    print("E boundary: exact non-literal net-initializer refusal")
    if not shutil.which("iverilog") or not shutil.which("vvp"):
        raise RuntimeError("Icarus is required for this source check")
    print(run(["iverilog", "-V"]).splitlines()[0])
    simulators = ["iverilog"]
    if shutil.which("xrun"):
        status, details = probe_xcelium()
        print(details)
        if status == 0:
            print(run(["xrun", "-version"]).strip())
            simulators.append("xrun")
        elif status == 77:
            print("no Xcelium result: explicit license refusal")
        else:
            raise RuntimeError("Xcelium readiness probe failed")
    else:
        print("no Xcelium result: xrun unavailable")
    for simulator in simulators:
        actual = source_rows(simulator)
        if actual != EXPECTED:
            raise RuntimeError(f"{simulator}: expected {EXPECTED}, got {actual}")
        print(f"{simulator}: {len(actual)} source rows MATCH")


if __name__ == "__main__":
    main()
