#!/usr/bin/env python3
"""Compare the retained PicoRV32 ALU body against Icarus and Xcelium."""

from pathlib import Path
import os
import shutil
import signal
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "harness/sv"))
from xcelium_probe import probe_xcelium  # noqa: E402


def run(args, cwd=ROOT):
    process = subprocess.Popen(args, cwd=cwd, text=True,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                               start_new_session=True)
    try:
        stdout, stderr = process.communicate(timeout=120)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
        stdout, stderr = process.communicate()
        raise RuntimeError(f"{args[0]} timed out:\n" + stdout + stderr)
    if process.returncode:
        raise RuntimeError(f"{args[0]} exited {process.returncode}:\n" + stdout + stderr)
    return stdout


def parse_rows(output):
    rows = []
    for line in output.splitlines():
        if line.startswith("ROW "):
            fields = line.split()
            values = [part.split("=", 1)[1] if "=" in part else part
                      for part in fields[2:]]
            rows.append([fields[1], *values])
    return rows


def check_envelope():
    with tempfile.TemporaryDirectory(prefix="sv-picorv32-alu-envelope-") as work:
        output = Path(work) / "body.sv.json"
        run([sys.executable, str(ROOT / "extractors/sv/extract.py"),
             "--top", "picorv32_alu_body_e", "--retain-proc-rewrites",
             "-o", str(output),
             str((HERE / "picorv32_alu_body_e.sv").relative_to(ROOT))])
        recorded = HERE / "picorv32_alu_body_e.sv.json"
        if output.read_bytes() != recorded.read_bytes():
            raise RuntimeError("retained envelope is not byte-identical to extraction")
    print("retained envelope regenerated byte-identically")


def source_rows(simulator):
    sources = [str(HERE / "picorv32_alu_body_e.sv"),
               str(HERE / "picorv32_alu_body_e_tb.sv")]
    with tempfile.TemporaryDirectory(prefix="sv-picorv32-alu-") as work:
        if simulator == "iverilog":
            exe = str(Path(work) / "sim")
            run(["iverilog", "-g2012", "-s", "picorv32_alu_body_e_tb",
                 "-o", exe] + sources, work)
            output = run(["vvp", exe], work)
        else:
            output = run(["xrun", "-sv", "-q", "-timescale", "1ns/1ps",
                          "-top", "picorv32_alu_body_e_tb"] + sources, work)
    return parse_rows(output)


def main():
    check_envelope()
    run(["lake", "build",
         "Examples.«system-verilog».sem2.picorv32_alu_body_e.agree"])
    e_rows = parse_rows(run(["lake", "env", "lean", "--run",
                             str(HERE / "oracle.lean")]))
    if len(e_rows) != 7:
        raise RuntimeError(f"E emitted {len(e_rows)} rows, expected 7: {e_rows}")
    print("E: 7 rows")

    if not shutil.which("iverilog") or not shutil.which("vvp"):
        raise RuntimeError("Icarus is required for this differential check")
    print(run(["iverilog", "-V"]).splitlines()[0])
    simulators = ["iverilog"]
    if shutil.which("xrun"):
        status, details = probe_xcelium()
        print(details)
        if status == 0:
            print(run(["xrun", "-version"]).strip())
            simulators.append("xrun")
        elif status == 77:
            print("no Xcelium result: explicit license refusal")
        else:
            raise RuntimeError("Xcelium readiness probe failed")
    else:
        print("no Xcelium result: xrun unavailable")

    for simulator in simulators:
        actual = source_rows(simulator)
        if actual != e_rows:
            raise RuntimeError(f"{simulator}: E {e_rows} != source {actual}")
        print(f"{simulator}: {len(actual)} rows MATCH E")


if __name__ == "__main__":
    main()
