def rel_posix(path):
    """Normalize a user-supplied path for use inside emitted files."""
    return os.path.normpath(path).replace(os.sep, "/")


def process_file(source_path, companion_dir, out=None):
    """Extract one source. ``out`` (leanpy's arbitrary-file mode) redirects
    the envelope to a directory or an explicit ``.json`` path; without it the
    envelope lands next to the source, as every in-tree example expects."""
    stem = os.path.splitext(os.path.basename(source_path))[0]
    if out is None and not STEM_RE.match(stem):
        raise ExtractError(
            "%s: stem %r is not a valid identifier (must match ^[A-Za-z_][A-Za-z0-9_]*$)"
            % (source_path, stem)
        )

    try:
        with open(source_path, "rb") as f:
            data = f.read()
    except OSError as e:
        raise ExtractError("%s: cannot read: %s" % (source_path, e))

    source_sha256 = hashlib.sha256(data).hexdigest()
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as e:
        raise ExtractError("%s: not valid UTF-8: %s" % (source_path, e))

    try:
        tree = ast.parse(text, filename=source_path)
    except SyntaxError as e:
        raise ExtractError("%s: syntax error: %s" % (source_path, e))

    blocks = scan_lean_blocks(text.splitlines(), source_path)

    # The two lowerings' shadow censuses (see `binds_any_name`): both are
    # whole-module, so both are decided once, here, before any expression
    # is converted.
    global _MODULE_BINDS_STR, _MODULE_SHADOWS_DISPLAY
    _MODULE_BINDS_STR = binds_any_name(tree, FSTRING_LOWERING_NAMES)
    _MODULE_SHADOWS_DISPLAY = binds_any_name(tree, DISPLAY_LOWERING_NAMES)

    source_rel = rel_posix(source_path)
    json_rel = os.path.splitext(source_rel)[0] + ".json"

    envelope = {
        "schema_version": SCHEMA_VERSION,
        "language": "python",
        "frontend": {"name": FRONTEND["name"], "version": FRONTEND["version"]},
        "source_file": source_rel,
        "source_sha256": source_sha256,
        "module": {"kind": "Module",
                   "body": [convert_stmt(s, module_scope=True)
                            for s in tree.body]},
        "lean_blocks": blocks,
    }

    if out is None:
        json_path = os.path.splitext(source_path)[0] + ".json"
    elif out.endswith(".json"):
        json_path = out
    else:
        json_path = os.path.join(out, stem + ".json")
    parent = os.path.dirname(json_path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(json_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(envelope, f, indent=2)
        f.write("\n")

    if not blocks:
        # Pure source (three-file per-example layout): envelope only. The
        # spec/proof .lean files are hand-written siblings, never generated.
        return

    if not STEM_RE.match(stem):
        raise ExtractError(
            "%s: stem %r is not a valid identifier (must match ^[A-Za-z_][A-Za-z0-9_]*$), "
            "so the '# lean[' blocks have no companion name" % (source_path, stem)
        )
    if companion_dir is None:
        # Default: the companion lives next to its source (per-example
        # directory layout — Examples/python/sum_to/sum_to.py → Examples/python/sum_to/).
        companion_dir = os.path.dirname(source_path) or "."
    companion_path = os.path.join(companion_dir, pascal_case(stem) + ".lean")
    check_companion_overwritable(companion_path)
    companion_text = generate_companion(stem, source_rel, json_rel, source_sha256, blocks)
    os.makedirs(companion_dir, exist_ok=True)
    with open(companion_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(companion_text)


def main(argv=None):
    sys.setrecursionlimit(10000)
    parser = argparse.ArgumentParser(
        prog="extract.py",
        description="Extract Python sources to envelope JSON + Lean companion files "
        "(run from the repo root).",
    )
    parser.add_argument("sources", nargs="+", metavar="file.py")
    parser.add_argument(
        "--companion-dir",
        default=None,
        help="directory for generated companion .lean files "
        "(default: the source file's own directory)",
    )
    parser.add_argument(
        "--out",
        default=None,
        metavar="DIR_OR_FILE.json",
        help="write the envelope here instead of next to the source "
        "(leanpy's arbitrary-file mode); an explicit .json path is allowed "
        "only with a single source",
    )
    args = parser.parse_args(argv)

    if args.out is not None and args.out.endswith(".json") and len(args.sources) > 1:
        print("error: --out <file.json> takes a single source (got %d)" % len(args.sources),
              file=sys.stderr)
        return 1

    try:
        for src in args.sources:
            process_file(src, args.companion_dir, args.out)
    except ExtractError as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
