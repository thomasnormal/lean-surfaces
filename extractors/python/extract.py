# Companion generation
# ---------------------------------------------------------------------------

def pascal_case(stem):
    """my_func -> MyFunc (split on '_', uppercase first letter of each part)."""
    return "".join(p[:1].upper() + p[1:] for p in stem.split("_"))


AUTOGEN_MARKER = "AUTOGENERATED by extractors/python/extract.py"


def header_lines(source_rel, source_sha256):
    """The companion's AUTOGENERATED header.

    Default form: a Lean block comment (kept byte-identical to the historical
    format so unchanged sources regenerate byte-stably). But the source path
    is embedded verbatim, and inside ``/- … -/`` a path containing ``/-``
    opens a *nested* block comment (resp. ``-/`` closes the header early) —
    the companion then dies with "unterminated comment" at EOF. Such paths
    (e.g. scratch roots with dash-leading segments) switch the whole header
    to ``--`` line comments, where both sequences are inert.
    """
    if "/-" in source_rel or "-/" in source_rel:
        return [
            "-- " + AUTOGEN_MARKER + " — DO NOT EDIT.",
            "-- source: " + source_rel,
            "-- sha256: " + source_sha256,
        ]
    return [
        "/-",
        AUTOGEN_MARKER + " — DO NOT EDIT.",
        "source: " + source_rel,
        "sha256: " + source_sha256,
        "-/",
    ]


def check_companion_overwritable(companion_path):
    """Hard error unless companion_path is absent or extractor-generated
    (AUTOGENERATED marker within its first three lines — where both header
    forms carry it). Never silently clobber a hand-written .lean file."""
    if not os.path.exists(companion_path):
        return
    try:
        with open(companion_path, "r", encoding="utf-8", errors="replace") as f:
            head = f.read(512)
    except OSError as e:
        raise ExtractError("%s: cannot read existing companion: %s"
                           % (companion_path, e))
    if not any(AUTOGEN_MARKER in ln for ln in head.split("\n")[:3]):
        raise ExtractError(
            "%s: refusing to overwrite — the existing file lacks the "
            "AUTOGENERATED header (hand-written?). Move it aside or pass a "
            "different --companion-dir." % companion_path
        )


def generate_companion(stem, source_rel, json_rel, source_sha256, blocks):
    hoisted = []  # deduped, order-preserving across all blocks
    block_bodies = []
    for b in blocks:
        body_lines = []
        for ln in b["text"].split("\n") if b["text"] != "" else []:
            if ln.startswith("import "):
                if ln not in hoisted:
                    hoisted.append(ln)
            else:
                body_lines.append(ln)
        block_bodies.append("\n".join(body_lines))

    parts = header_lines(source_rel, source_sha256) + [
        "import LeanModels",
    ]
    parts.extend(hoisted)
    parts.append("")
    parts.append("open LeanModels LeanModels.Python")
    parts.append("")
    parts.append('load_program %s from "%s"' % (stem, json_rel))
    for body in block_bodies:
        if body.strip() == "":
            continue  # block contained only imports (or nothing)
        parts.append("")
        parts.append(body)
    return "\n".join(parts) + "\n"


