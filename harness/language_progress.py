#!/usr/bin/env python3
"""Keep the README language progress table in sync with coverage pages.

The coverage pages are generated by each language's harness.  This small
renderer deliberately reads those committed pages instead of running the
harnesses again, so it is cheap enough for every CI check and for contributors
updating one language at a time.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- LANGUAGE_PROGRESS:START -->"
END = "<!-- LANGUAGE_PROGRESS:END -->"


def _row_after_heading(text: str, heading: str, header: str) -> tuple[int, int]:
    """Return the first two numeric cells in a named coverage table."""
    try:
        section = text[text.index(heading) :]
    except ValueError as exc:
        raise ValueError(f"missing coverage heading {heading!r}") from exc
    pattern = (
        rf"\| {re.escape(header)} \|[^\n]*\n"
        rf"\|[-:| ]+\n"
        rf"\|\s*(\d+)\s*\|\s*(\d+)\s*\|"
    )
    match = re.search(pattern, section)
    if not match:
        raise ValueError(f"missing {header!r} table row after {heading!r}")
    return int(match.group(1)), int(match.group(2))


def _python_rows() -> tuple[int, int, int, int]:
    text = (ROOT / "docs/python-coverage.md").read_text(encoding="utf-8")
    rows, match = _row_after_heading(text, "## Differential pass rate", "rows")
    proof_rows, proof_match = _row_after_heading(
        text, "### What the theorems can see", "rows"
    )
    if proof_rows != rows:
        raise ValueError("Python proof and runner coverage use different row counts")
    return rows, match, proof_rows, proof_match


def _coverage_rows() -> dict[str, tuple[int, int]]:
    python_rows, python_match, _, _ = _python_rows()
    cpp_text = (ROOT / "docs/cpp-coverage.md").read_text(encoding="utf-8")
    cpp_rows, cpp_match = _row_after_heading(cpp_text, "## Differential table", "rows")
    sv_text = (ROOT / "docs/sv-coverage.md").read_text(encoding="utf-8")
    sv_rows, sv_match = _row_after_heading(
        sv_text, "## Differential self-consistency", "rows"
    )
    return {
        "Python": (python_rows, python_match),
        "C++": (cpp_rows, cpp_match),
        "SystemVerilog": (sv_rows, sv_match),
    }


def _percent(match: int, rows: int) -> str:
    if rows <= 0:
        return "0.0"
    return f"{100.0 * match / rows:.1f}"


def _bar(percent: str) -> str:
    return (
        f'<progress value="{percent}" max="100" '
        f'aria-label="{percent}% complete">{percent}%</progress> **{percent}%**'
    )


def render_table() -> str:
    rows = _coverage_rows()
    py_total, py_match = rows["Python"]
    py_proof_total, py_proof_match = _python_rows()[2:]
    cpp_total, cpp_match = rows["C++"]
    sv_total, sv_match = rows["SystemVerilog"]
    return "\n".join(
        [
            START,
            "<!-- GENERATED by harness/language_progress.py — do not edit. -->",
            "",
            "These bars use each tier's checked-in differential corpus: `MATCH` "
            "rows divided by all rows, rounded to one decimal place. The linked "
            "coverage pages are the source of truth; this table is regenerated "
            "by `harness/language_progress.py`.",
            "",
            "| Language | Completion | Current measurement |",
            "| --- | --- | --- |",
            f"| Python | {_bar(_percent(py_match, py_total))} | "
            f"{py_match:,} / {py_total:,} differential rows "
            f"([coverage](docs/python-coverage.md)); proof interpreter: "
            f"{py_proof_match:,} / {py_proof_total:,} |",
            f"| C++ | {_bar(_percent(cpp_match, cpp_total))} | "
            f"{cpp_match:,} / {cpp_total:,} differential rows "
            f"([coverage](docs/cpp-coverage.md)) |",
            f"| Rust | {_bar('0.0')} | Lane planned, implementation not started "
            f"([roadmap](#roadmap-not-built--do-not-expect-it-in-this-tree)) |",
            f"| SystemVerilog | {_bar(_percent(sv_match, sv_total))} | "
            f"{sv_match:,} / {sv_total:,} differential self-check rows "
            f"([coverage](docs/sv-coverage.md)) |",
            END,
        ]
    )


def update_readme(text: str, table: str) -> str:
    pattern = re.compile(
        rf"{re.escape(START)}.*?{re.escape(END)}", re.DOTALL
    )
    if not pattern.search(text):
        raise ValueError("README is missing the language progress markers")
    return pattern.sub(table, text, count=1)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if README is stale")
    args = parser.parse_args()
    table = render_table()
    current = README.read_text(encoding="utf-8")
    updated = update_readme(current, table)
    if args.check:
        if current != updated:
            print("language_progress: README.md is stale; run this script")
            return 1
        print("language_progress: README.md is fresh")
        return 0
    if current != updated:
        with README.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(updated)
        print("language_progress: updated README.md")
    else:
        print("language_progress: README.md is already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
