#!/usr/bin/env python3
"""Generate the Step 4 E combinational receipt page.

The selected source-shaped comb rows are sent to one batched ``diff_test2``
process.  The page is derived from that receipt; it is never hand-maintained.
"""

import argparse
import re
import subprocess
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "sv-e-comb-rows.md"

COMB_CASES = [
    "xnor_n", "fa_comb_proc", "addsub_comb", "addsub_comb_n1", "addsub_comb_n8",
    "acg_temp_all", "acg_two_temps", "acg_bits_ok", "acg_part_ok", "acg_case_ok",
    "acg_cond_ok", "acg_nested_ok", "acg_latch_read", "acg_xproc_bits",
    "acg_alias_bits_ok", "acg_alias_bits", "acg_alias_assign", "acg_alias_port",
    "acg_alias_chain", "acg_alias_not", "acg_alias_wire", "acg_alias_hier",
    "acg_alias_thru", "acg_alias_wr", "acg_alias_copy", "acg_alias_far",
    "acg_alias_hier_ok", "acg_alias_port_wr", "latch_comb", "rbw_comb", "t2_combw",
    "t2_ci", "mux4_case", "onehot_dec", "wpg_if_x", "wpg_if_chain", "wpg_tern_x",
    "wpg_tern_ctx", "wpg_order", "wpg_carry", "wpg_local", "wpg_partial", "wpg_not",
    "wpg_red", "wpg_logic", "xcelium_qualified_ops", "streaming_left_fixed",
    "streaming_pack_fixed", "streaming_leading_bits", "member_elem_union",
]

LINE = re.compile(r"^(?P<name>\S+)\s+(?P<verdict>PASS|REFUSED|CHECKED|UNAVAILABLE ORACLE|ERROR|FAIL|DECLARED SIMULATOR DISAGREEMENT|TIMEOUT)(?:.*?\((?P<cycles>\d+) cycles\))?", re.M)


def run(sim):
    """Run each row with a bounded child, retaining timeout/error receipts."""
    def one(name):
        cmd = ["python3", "harness/sv/diff_test2.py", "--backend", "e0",
               "--sim", sim, "--no-xcheck", "--case", name]
        try:
            p = subprocess.run(cmd, cwd=ROOT, text=True, stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, timeout=120, check=False)
            return p.stdout
        except subprocess.TimeoutExpired:
            return "%s TIMEOUT (generator child exceeded 120 seconds)\n" % name
    with ThreadPoolExecutor(max_workers=8) as pool:
        outputs = list(pool.map(one, COMB_CASES))
    class Receipt:
        returncode = 0
        stdout = "".join(outputs)
    return Receipt()


def parse(text):
    rows = {}
    for m in LINE.finditer(text):
        rows[m.group("name")] = (m.group("verdict"), m.group("cycles") or "—")
    return rows


def shapes():
    cases = json.loads((ROOT / "harness" / "sv" / "cases2.json").read_text())["cases"]
    by_name = {c["name"]: c for c in cases}
    out = {}
    for name in COMB_CASES:
        c = by_name[name]
        base = c.get("file", c["top"])
        env = ROOT / "Examples" / "system-verilog" / c["example"] / (base + ".sv.json")
        kinds = set()
        try:
            data = json.loads(env.read_text())
            def walk(x):
                if isinstance(x, dict):
                    if x.get("kind") in {"Assign", "AlwaysComb"}:
                        kinds.add(x["kind"])
                    for v in x.values(): walk(v)
                elif isinstance(x, list):
                    for v in x: walk(v)
            walk(data.get("design", data))
        except (OSError, ValueError):
            pass
        out[name] = "+".join(sorted(kinds)) or "source-shaped comb"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sim", default="both", choices=["both", "xrun", "iverilog"])
    ap.add_argument("--output", default=str(OUT))
    args = ap.parse_args()
    p = run(args.sim)
    rows = parse(p.stdout)
    shape = shapes()
    missing = [n for n in COMB_CASES if n not in rows]
    if missing:
        raise SystemExit("generator: missing receipt rows: " + ", ".join(missing))
    lines = [
        "# E combinational row probe",
        "",
        "<!-- GENERATED by harness/sv/generate_e_comb_rows.py; do not edit. -->",
        "<!-- Source: harness/sv/cases2.json; backend: e0; simulator request: %s. -->" % args.sim,
        "",
        "This page is generated from one batched E differential run over the committed source-shaped envelopes.",
        "The frozen migration number is 554/684; these Step 4 receipts are reported separately.",
        "",
        "| row | shape | cycles | verdict | simulators |",
        "| --- | --- | ---: | --- | --- |",
    ]
    for name in COMB_CASES:
        verdict, cycles = rows[name]
        lines.append("| `%s` | %s | %s | %s | Icarus 13.0 / Xcelium 24.03-s004 |" %
                     (name, shape[name], cycles, verdict))
    lines += ["", "Generated from the committed envelopes and the differential harness receipts; unavailable simulators are retained as explicit verdicts.", ""]
    Path(args.output).write_text("\n".join(lines))
    print(p.stdout, end="")
    return p.returncode


if __name__ == "__main__":
    raise SystemExit(main())
