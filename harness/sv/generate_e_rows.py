#!/usr/bin/env python3
"""Generate the aggregate Step 4 E-row page from its frozen measurement."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = ROOT / "harness" / "sv" / "e_rows_snapshot.json"
OUTPUT = ROOT / "docs" / "sv-e-rows.md"


def render(data):
    outcomes = data["outcomes"]
    total = sum(row["count"] for row in outcomes)
    if total != data["oracle_rows"]:
        raise SystemExit("e-row snapshot counts do not sum to oracle_rows")
    current = data["current"]
    triage = {row["row"]: row for row in current["triage"]}
    if set(triage) != {"dyn32", "fold_cgrow_n33", "fold_cgrow_n40"}:
        raise SystemExit("e-row snapshot must contain the three divergence rows")
    lines = [
        "# E row baseline (Step 4)",
        "",
        "<!-- GENERATED by harness/sv/generate_e_rows.py; do not edit. -->",
        "<!-- Source: harness/sv/e_rows_snapshot.json; source cases: %s. -->" % data["source"],
        "",
        "This page is generated from the committed Step 4 E measurement snapshot. The snapshot records the frozen run; it is not a hand-maintained row verdict.",
        "",
        "The source is the committed `harness/sv/cases2.json` at the S0.e measurement. The %d oracle row names have SHA-256 `%s`." %
        (data["oracle_rows"], data["row_names_sha256"]),
        "The baseline used backend `%s`, the committed envelopes, %s, a %d-second wall limit, %d workers, and no multi-point cross-check." %
        (data["frozen_baseline"]["backend"], " and ".join(data["frozen_baseline"]["simulators"]),
         data["frozen_baseline"]["wall_seconds"], data["frozen_baseline"]["workers"]),
        "",
        "| outcome | rows | first examples or boundary |",
        "| --- | ---: | --- |",
    ]
    for row in outcomes:
        lines.append("| %s | %d | `%s` |" % (row["label"], row["count"], "`, `".join(row["examples"])))
    lines += [
        "",
        "Thus the initial migration number is **547 E-MATCH rows out of 684**. The three measured divergences and the 16 declared divergences remain separate from E-MATCH; no row is silently counted as agreement.",
        "",
        "The 2026-11-12 triage closed the two `fold_cgrow` rows (`fold_cgrow_n33` and `fold_cgrow_n40`) by evaluating typed generate guards at their own widths, so the current E count is **%d/684**. `dyn32` follows the unsigned 32-bit base rule and retains only the registered Xcelium partial-overhang behavior; it is not counted as an E-MATCH." % current["e_matches"],
        "",
        "The three historical measured-divergence rows were re-run by `harness/sv/check_e_divergences.py`: `fold_cgrow_n33` and `fold_cgrow_n40` are ordinary E/Icarus matches, while `dyn32` is an E/Icarus match with the registered Xcelium partial-overhang departure. The gate treats any new E disagreement or refusal as a failure.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=str(OUTPUT))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(SNAPSHOT.read_text()))
    output = Path(args.output)
    if args.check:
        if output.read_text() != text:
            raise SystemExit("generated E-row page is stale")
    else:
        output.write_text(text)
    print("generate_e_rows: OK")


if __name__ == "__main__":
    main()
