#!/usr/bin/env python3
"""Generate the public REAL-DESIGNS admission table from pinned receipts."""

from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "sv-real-designs.md"

# These are the checked-in census receipts for the pinned public sources.  The
# output table is generated; changing a result requires changing its measured
# receipt and rerunning this script.
ROWS = [
    ("prim_fifo_sync", "OpenTitan 0a6ff685", "37", "no", "PortSymbol:type (parameterized unpacked ports)"),
    ("prim_arbiter_ppc", "OpenTitan 0a6ff685", "11", "no", "PortSymbol:type (parameterized unpacked ports)"),
    ("prim_packer", "OpenTitan 0a6ff685", "20", "no", "ConversionExpression:explicit"),
    ("CV32E40P", "openhwgroup v1.0.1 / 6148cf5", "574", "no", "AlwaysPosedge:edge"),
    ("Ibex", "lowRISC d513671d", "396", "no", "AlwaysLatch:unknown process kind"),
    ("PicoRV32", "YosysHQ ef203c2b", "70", "loader yes; E no", "Instantiate: cpuregs unpacked memory"),
    ("DarkRISCV", "darklife bb6b483c", "1", "no", "Constant: non-literal FLUSH initializer"),
]

lines = [
    "# REAL-DESIGNS admission census",
    "",
    "<!-- GENERATED by harness/sv/generate_real_designs.py; do not edit. -->",
    "",
    "This table is generated from the pinned public-design census receipts. It measures loading and the first E wall for each source as written; no RTL was adapted.",
    "",
    "| design | pinned source | unsupported nodes | loads into E | first E wall |",
    "| --- | --- | ---: | --- | --- |",
]
for row in ROWS:
    lines.append("| `%s` | %s | %s | %s | `%s` |" % row)
lines += ["", "The three OpenTitan rows use the F1-retention census in `docs/sv-frontier.md`; CV32E40P and the RISC-V scouting rows use `Examples/system-verilog/cores/README.md` and `docs/cv32e40p-census.json`. The table is an admission census, not a proof claim.", ""]
generated = "\n".join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true",
                    help="verify the checked-in page is exactly generated")
args = parser.parse_args()
if args.check:
    current = OUT.read_text() if OUT.exists() else None
    if current != generated:
        raise SystemExit(f"generated page is stale: {OUT}")
    print(f"checked {OUT}")
else:
    OUT.write_text(generated)
    print(OUT)
