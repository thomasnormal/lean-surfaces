#!/usr/bin/env python3
"""Pinned Xcelium reference traces for the SV phase-2 differential corpus.

Xcelium is the REFERENCE simulator for ls-sv (Thomas, 2026-10-29): when the
model and Xcelium differ the model is suspect. Xcelium is NOT available
everywhere, so its results are PINNED DATA -- `harness/sv/xcelium_golden.json`
-- that anyone can compare against without access. Nothing in CI, the harness
defaults or the svGolf checker requires Xcelium; this module is stdlib-only and
is the single place that defines the golden file format and its content hash.

  * `row_hash`   -- the content hash a golden entry is keyed by;
  * `load` / `save` -- the file, deterministic bytes (sorted rows, fixed indent);
  * `Xref`       -- what `diff_test2.py --golden` uses to compare a model trace
                    with the pinned Xcelium trace (XREF-MATCH / -DECLARED /
                    -DIFF / -STALE / -NONE).

The file is produced by `harness/sv/xcelium_batch.py` (see
docs/sv-xcelium-reference.md for the refresh procedure). Row layout:

    "rows": { "<row name>": { "hash": "<sha256>", "status": "<status>",
                              "cycles": ["CYCLE 0 ...", ...],   # stdout CYCLE lines
                              "message": "<tool message, failures only>" } }

Statuses: `ok` (xrun exited 0 and reached `$finish`), `xrun-compile-error`
(xmvlog/xmelab/xrun diagnostics: Xcelium rejects the source), `runtime-error`
(xmsim error, nonzero exit, or no `$finish`), `timeout` (refsim's 900 s cap),
`no-testbench` (the model could not produce the port list the testbench needs,
so no Xcelium run was possible; `hash` is null).
"""

import hashlib
import json
import os

HARNESS_DIR = os.path.dirname(os.path.abspath(__file__))
GOLDEN_JSON = os.path.join(HARNESS_DIR, "xcelium_golden.json")
FORMAT = 1

# The simulator flags that decide the observed trace. They are part of the
# content hash, so changing them makes every pinned entry stale. (Where the
# library directory lives -- `-xmlibdirname` -- is not semantic and is not
# hashed.)
XRUN_FLAGS = ["-sv", "-q", "-timescale", "1ns/1ns"]

HASH_SCHEME = ("sha256 of the canonical JSON (sorted keys, no whitespace, ASCII) "
               "of {row, dut, tb, params, xrun_flags}: the row name, the DUT "
               "source text, the generated testbench text, the row's parameter "
               "overrides and the semantic xrun flags")

# Statuses for which an Xcelium trace exists and is meaningful to compare.
STATUS_OK = "ok"
FAILURE_STATUSES = ("xrun-compile-error", "runtime-error", "timeout", "no-testbench")


def row_hash(name, dut_text, tb_text, params):
    """The content hash of one row: (DUT source, testbench, params, row name,
    xrun flags). `dut_text` / `tb_text` are `str`; `params` the row's override
    dict (or None)."""
    blob = json.dumps(
        {"row": name, "dut": dut_text, "tb": tb_text,
         "params": {k: params[k] for k in sorted(params or {})},
         "xrun_flags": XRUN_FLAGS},
        sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


def read_text(path):
    """A source file as `str`, byte-exact round trip (undecodable bytes are
    carried as lone surrogates, which the hash then escapes)."""
    with open(path, "rb") as handle:
        return handle.read().decode("utf-8", "surrogateescape")


COMMENT = ("Pinned Xcelium reference traces for harness/sv/cases2.json (docs/sv-xcelium-reference.md). "
           "Generated by harness/sv/xcelium_batch.py; do not edit by hand. Compared by "
           "diff_test2.py --golden; usable without Xcelium.")


def empty_golden():
    return {"_comment": COMMENT, "format": FORMAT, "simulator": {}, "hash_scheme": HASH_SCHEME,
            "rows": {}}


def load(path=None):
    """The golden file as a dict, or None when it does not exist."""
    path = path or GOLDEN_JSON
    if not os.path.exists(path):
        return None
    with open(path) as handle:
        golden = json.load(handle)
    if golden.get("format") != FORMAT:
        raise ValueError("%s: unknown golden format %r (want %d)"
                         % (path, golden.get("format"), FORMAT))
    return golden


def dumps(golden):
    """Deterministic serialization: rows sorted by name, one cycle per line."""
    out = dict(golden)
    out.setdefault("_comment", COMMENT)
    out["rows"] = {k: golden["rows"][k] for k in sorted(golden["rows"])}
    return json.dumps(out, indent=1, sort_keys=True, ensure_ascii=True) + "\n"


def save(golden, path=None):
    """Atomic write (temp file + rename), so a dropped run never leaves a
    half-written golden file."""
    path = path or GOLDEN_JSON
    tmp = path + ".tmp"
    with open(tmp, "w") as handle:
        handle.write(dumps(golden))
    os.replace(tmp, path)


class Xref:
    """The `diff_test2.py --golden` comparison against a pinned file.

    `check(name, case, dut_sv, tb, model_traces)` classifies one simulated
    row: XREF-MATCH (hash matches, Xcelium ok, its trace equals the model's
    for some accepted schedule), XREF-DIFF (same but the traces differ),
    XREF-STALE (the pinned hash no longer matches the sources: the golden
    entry describes other sources, so nothing is claimed), XREF-NONE (no
    usable Xcelium trace: the row is not pinned, or Xcelium could not take it).

    A row that carries an `oracle_disagreement` declaration naming Xcelium
    (round 6, docs/sv-oracle-disagreements.md) is checked through the
    `declaration` argument of `check`: the pin plays the simulator, and the
    row is XREF-DECLARED -- counted apart from XREF-MATCH and XREF-DIFF, never
    a match -- exactly when the pinned and the model trace are the recorded
    ones. A declared departure that has been resolved or has changed is not a
    status: the declaration raises `HarnessError`, a hard failure of the run.
    """

    def __init__(self, path=None):
        self.path = path or GOLDEN_JSON
        self.golden = load(self.path)
        if self.golden is None:
            raise FileNotFoundError(
                "no golden file at %s (refresh it with harness/sv/xcelium_batch.py, "
                "see docs/sv-xcelium-reference.md)" % self.path)
        self.counts = {"match": 0, "declared": 0, "diff": 0, "stale": 0, "none": 0}

    @property
    def version(self):
        return (self.golden.get("simulator") or {}).get("version", "unknown")

    def check(self, name, dut_sv, tb, params, model_traces, diff_traces, declaration=None):
        """Returns `(status, detail_lines)`; counts the status. `model_traces`:
        the model's traces for the accepted schedules (a list of line lists).
        `diff_traces(sim, lean)`: the harness's trace differ. `declaration`:
        for a row that declares an Xcelium departure, a callable taking the
        pinned trace (or None when no usable pin exists) and returning the
        declaration id; it raises `HarnessError` for a changed input, a
        resolved departure or a changed trace (`diff_test2` builds it from
        `oracle_disagreements.golden_disagreement`)."""
        entry = self.golden["rows"].get(name)
        if entry is None:
            self.counts["none"] += 1
            return "XREF-NONE", self._unchecked(declaration, "no pinned Xcelium entry for this row")
        now = row_hash(name, read_text(dut_sv), tb, params)
        if entry.get("hash") != now:
            self.counts["stale"] += 1
            return "XREF-STALE", self._unchecked(declaration, (
                "the DUT / testbench / parameters changed since the pin (%s... vs %s...): "
                "refresh harness/sv/xcelium_golden.json (warning, not a failure)"
                % ((entry.get("hash") or "none")[:10], now[:10])))
        if entry.get("status") != STATUS_OK:
            self.counts["none"] += 1
            msg = (entry.get("message") or "").strip().splitlines()
            return "XREF-NONE", self._unchecked(declaration, "Xcelium %s: %s" % (
                entry.get("status"), msg[0] if msg else "(no message)"))
        xtrace = entry["cycles"]
        if declaration is not None:
            ident = declaration(xtrace)
            if ident:
                self.counts["declared"] += 1
                return "XREF-DECLARED", [
                    "declared Xcelium departure %s: the pinned trace and the model trace are the "
                    "recorded ones (not a match)" % ident]
        if any(xtrace == m for m in model_traces):
            self.counts["match"] += 1
            return "XREF-MATCH", []
        self.counts["diff"] += 1
        return "XREF-DIFF", (diff_traces(xtrace, model_traces[0]) or "").split("\n")

    @staticmethod
    def _unchecked(declaration, line):
        """The detail of a status that carries no usable pin. A declared Xcelium
        departure then cannot be re-checked against the pin, but its input
        bindings still are (a changed source raises `HarnessError`)."""
        if declaration is None:
            return [line]
        ident = declaration(None)
        return [line, "declared Xcelium departure %s: NOT re-checked against the pin (input bindings only)"
                % ident]

    def summary(self):
        c = self.counts
        return ("xref vs pinned Xcelium %s: %d XREF-MATCH, %d XREF-DECLARED, %d XREF-DIFF, "
                "%d XREF-STALE, %d XREF-NONE"
                % (self.version, c["match"], c["declared"], c["diff"], c["stale"], c["none"]))
