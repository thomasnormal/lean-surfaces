#!/usr/bin/env python3
"""Generate ``docs/sv-coverage.md`` from the SV differential instruments."""

import argparse
import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "sv-coverage.md"


def run_json(script):
    p = subprocess.run([sys.executable, str(REPO / "harness" / script), "--json"],
                       cwd=str(REPO), capture_output=True, text=True, timeout=3600)
    if p.returncode:
        raise SystemExit("%s failed (%d):\n%s\n%s" %
                         (script, p.returncode, p.stdout[-2000:], p.stderr[-2000:]))
    try:
        return json.loads(p.stdout)
    except ValueError as exc:
        raise SystemExit("%s did not emit JSON: %s\n%s" % (script, exc, p.stdout[-2000:]))


def census_summary():
    path = REPO / "docs" / "sv-construct-census.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    summary = data["summary"]
    return data["provenance"], summary


def render(diff, grammar, provenance, census):
    corpus = census.get("by_status", {})
    grammar_total = grammar["witnesses"]
    grammar_match = grammar["match"]
    corpus_total = sum(corpus.get(k, 0) for k in
                       ("clean", "partial", "skip_include"))
    corpus_clean = corpus.get("clean", 0)

    lines = [
        "# SystemVerilog coverage",
        "",
        "<!-- GENERATED by harness/sv_coverage_page.py — do not edit. -->",
        "",
        "The legacy self-check runner remains initial-only; the timed "
        "conformance path now admits plain `always` and `always_comb` "
        "processes, while other "
        "non-initial processes remain refused. This page therefore leads with "
        "grammar and corpus measurements, then reports differential "
        "self-consistency separately. It is generated from the SystemVerilog "
        "self-check interpreter, the pinned sv-tests-2 declarations, and "
        "pyslang's syntax kinds. A host-local simulator is optional and is "
        "accepted only through `SV_ORACLE_CMD`; its name and path are never "
        "part of the repository.",
        "",
        "## Measured coverage",
        "",
        "Grammar coverage counts MATCH syntax kinds over every kind found in "
        "the checked-in examples; REFUSE is uncovered. The corpus share counts "
        "sv-tests-2 paths whose extraction envelope has no Unsupported nodes. "
        "The corpus census is an extraction measurement, not an execution run "
        "of every external test; executable differential rows are reported "
        "below.",
        "",
        "| measurement | covered | total | share |",
        "|---|---:|---:|---:|",
        "| grammar syntax kinds (MATCH) | {gm} | {gt} | {gps:.1f}% |".format(
            gm=grammar_match, gt=grammar_total,
            gps=100.0 * grammar_match / grammar_total if grammar_total else 0.0),
        "| sv-tests-2 paths with clean extraction | {cc} | {ct} | {cps:.1f}% |".format(
            cc=corpus_clean, ct=corpus_total,
            cps=100.0 * corpus_clean / corpus_total if corpus_total else 0.0),
        "",
        "## Differential self-consistency",
        "",
        "The rows in `harness/sv_cases.json` carry `expect: match|refuse`. A "
        "match compares every emitted `$display` line with the row's committed "
        "declaration. A recorded refusal passes only when Lean returns a loud "
        "`unsupported` result with a non-empty reason. This agreement rate "
        "measures consistency on the tier's selected witness rows; it is not a "
        "language-spec completion percentage.",
        "",
        "| rows | agree | disagree | recorded refusals | oracle |",
        "|---:|---:|---:|---:|---|",
        "| {rows} | {agree} | {disagree} | {refused} | {oracle} |".format(
            rows=diff["rows"], agree=diff["agree"], disagree=diff["disagree"],
            refused=diff["recorded_refusals"], oracle=diff["oracle"]),
        "",
        "| case | source | expectation | verdict | model status | detail |",
        "|---|---|---|---|---|---|",
    ]
    for row in diff["results"]:
        detail = " ".join(row["detail"].split()).replace("|", "\\|")
        lines.append("| `{name}` | `{file}` | {expect} | **{verdict}** | `{status}` | {detail} |".format(
            name=row["name"], file=row["file"], expect=row["expect"],
            verdict=row["verdict"], status=row["model_status"], detail=detail))
    lines += [
        "",
        "## Grammar census",
        "",
        "One witness source is retained for every pyslang `SyntaxKind` found in "
        "the checked-in examples. `MATCH` means the frontend parsed and the "
        "self-check interpreter completed; `REFUSE` records the first loud "
        "boundary for that witness. This is a syntax lower bound, not a claim "
        "that every context of a kind is admitted.",
        "",
        "| witnesses | MATCH | REFUSE | frontend |",
        "|---:|---:|---:|---|",
        "| {w} | {m} | {r} | pyslang SyntaxKind |".format(
            w=grammar["witnesses"], m=grammar["match"], r=grammar["refuse"]),
        "",
        "| syntax kind | witness | verdict | model status / detail |",
        "|---|---|---|---|",
    ]
    for row in grammar["rows"]:
        detail = " ".join(row["detail"].split()).replace("|", "\\|")
        lines.append("| `{}` | `{}` | **{}** | `{}` {} |".format(
            row["kind"], row["witness"], row["verdict"], row["model"], detail))
    lines += [
        "",
        "## Corpus validation",
        "",
        "The extractor census is validation on real sv-tests-2 files; it is "
        "separate from the executable grammar and differential rows above.",
        "",
        "| corpus paths | clean | partial | include skips |",
        "|---:|---:|---:|---:|",
        "| {total} | {clean} | {partial} | {skip} |".format(
            total=sum(corpus.get(k, 0) for k in ("clean", "partial", "skip_include")),
            clean=corpus.get("clean", 0), partial=corpus.get("partial", 0),
            skip=corpus.get("skip_include", 0)),
        "",
        "| blocker kind | files |",
        "|---|---:|",
    ]
    for kind, count in census.get("blocker_files", [])[:15]:
        lines.append("| `{}` | {} |".format(kind, count))
    frontend = provenance.get("frontend", {})
    lines += [
        "",
        "The committed census provenance identifies frontend family `{}` and "
        "corpus `{}`. The corpus snapshot is not silently substituted when the "
        "external checkout is unavailable.".format(
            frontend.get("family", "unknown"), provenance.get("corpus_name", "unknown")),
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    diff = run_json("sv_diff_test.py")
    grammar = run_json("sv_grammar_census.py")
    provenance, census = census_summary()
    text = render(diff, grammar, provenance, census)
    if args.check:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != text:
            print("sv_coverage_page: stale %s" % OUT, file=sys.stderr)
            return 1
    else:
        with OUT.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("wrote %s (%d grammar witnesses, %d differential rows)" %
              (OUT, grammar["witnesses"], diff["rows"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
